/*
 * Generates js/portfolio-data.js from the real image folders.
 *
 * The folder structure under assets/images/ is the source of truth:
 *
 *   assets/images/portfolio/<category>/...   full-resolution photographs
 *   assets/images/thumbnails/<category>/...  optimized previews
 *
 * Running `node scripts/build-portfolio-data.js` keeps the category list and
 * image lists in sync with whatever is physically present.
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const PORTFOLIO_DIR = path.join(ROOT, 'assets', 'images', 'portfolio');
const THUMBNAILS_DIR = path.join(ROOT, 'assets', 'images', 'thumbnails');
const OUT_FILE = path.join(ROOT, 'js', 'portfolio-data.js');

const DISPLAY_NAMES = {
  astrophotography: 'Astrophotography',
  car: 'Car',
  landscape: 'Landscape',
  lifestyle: 'Lifestyle',
  micro: 'Micro',
  nature: 'Nature',
  portrait: 'Portraits',
  'still life': 'Still Life',
  street: 'Street',
};

const DESCRIPTIONS = {
  astrophotography: 'The night sky, stars and deep-space objects captured long after dark.',
  car: 'Detail and motion studies of cars — paint, glass, light and lines.',
  landscape: 'Wide scenic views of mountains, water and open skies.',
  lifestyle: 'Candid, in-between moments that tell everyday stories.',
  micro: 'A close look at tiny subjects — insects, textures and hidden detail.',
  nature: 'Plants, animals and the quiet beauty of the outdoors.',
  portrait: 'People-focused work, from environmental shots to clean headshots.',
  'still life': 'Carefully arranged objects explored for light, form and mood.',
  street: 'Life on the streets — candid scenes, people and urban rhythm.',
};

function listFiles(dir) {
  const entries = fs.readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isFile())
    .map((e) => e.name)
    .filter((name) => /\.(jpe?g|png|webp|gif|avif)$/i.test(name))
    .sort();
  return entries;
}

function listCategories(dir) {
  return fs.readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .sort();
}

function identifyCategory(name, folderName, portfolioFiles, thumbFiles) {
  if (portfolioFiles.length === 0 || thumbFiles.length === 0) return null;

  const shared = thumbFiles.filter((f) => portfolioFiles.includes(f));
  const representative = shared[0] || thumbFiles[0] || portfolioFiles[0];

  return {
    id: folderName,
    name: DISPLAY_NAMES[name] || prettyName(folderName),
    description: DESCRIPTIONS[name] || '',
    preview: `${folderName}/${representative}`,
    images: portfolioFiles
      .map((f) => ({
        thumb: `thumbnails/${folderName}/${f}`,
        full: `portfolio/${folderName}/${f}`,
      })),
  };
}

function prettyName(raw) {
  return raw
    .split(/[_\-\s]+/)
    .filter(Boolean)
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join(' ');
}

function escapeJs(value) {
  return String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

function main() {
  const categoryNames = [...new Set([
    ...listCategories(PORTFOLIO_DIR),
    ...listCategories(THUMBNAILS_DIR),
  ])];

  const categories = categoryNames
    .map((folderName) => {
      const portfolioFiles = listFiles(path.join(PORTFOLIO_DIR, folderName));
      const thumbFiles = listFiles(path.join(THUMBNAILS_DIR, folderName));
      return identifyCategory(folderName, folderName, portfolioFiles, thumbFiles);
    })
    .filter(Boolean);

  const lines = [];
  lines.push('/* Auto-generated by scripts/build-portfolio-data.js.');
  lines.push('   Run `node scripts/build-portfolio-data.js` after adding images');
  lines.push('   or categories so the lists stay in sync with the folders. */');
  lines.push('');
  lines.push('window.PHOTO_CATEGORIES = [');
  categories.forEach((cat) => {
    lines.push(`  {`);
    lines.push(`    id: '${escapeJs(cat.id)}',`);
    lines.push(`    name: '${escapeJs(cat.name)}',`);
    lines.push(`    description: '${escapeJs(cat.description)}',`);
    lines.push(`    preview: '${escapeJs(cat.preview)}',`);
    lines.push(`    images: [`);
    cat.images.forEach((img) => {
      lines.push(`      { thumb: '${escapeJs(img.thumb)}', full: '${escapeJs(img.full)}' },`);
    });
    lines.push(`    ],`);
    lines.push(`  },`);
  });
  lines.push('];');
  lines.push('');

  if (categories.length === 0) {
    console.warn('No categories found. Nothing written.');
    return;
  }

  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
  fs.writeFileSync(OUT_FILE, lines.join('\n'), 'utf8');
  console.log(`Wrote ${OUT_FILE} (${categories.length} categories, ` +
    `${categories.reduce((n, c) => n + c.images.length, 0)} images).`);
}

try {
  main();
} catch (err) {
  console.error('Failed to generate portfolio data:', err.message);
  process.exit(1);
}